#!/usr/bin/env python3
"""Run: python3 /absolute/path/to/polly/scripts/generate-web-design.py [--check]

Extract the archived design without executing its bundled runtime. No network needed.
"""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "doc/design/polly-web/source"
PUBLIC = ROOT / "Packages/PollyWeb/Sources/PollyWeb/Public"
HASHES = {
    "Polly Design System.dc.html": "061de785163967b061f75ae565419b01ef404ed8c1e26574b298831b8a1a2e7f",
    "Polly Animations.dc.html": "2239499aba2df81bbbc694aacc4ea4a9b889a568f24ab0b4f41c9d348e7803c7",
    "Polly Animations.html": "b4f628280da395b0f33c04b219bfa90714d9613153a07a3f4b6fa12dbe5e57c7",
    "PollyMascot.dc.html": "906fce923ec5e71bc9c16509e45103d5713ae8db2d0bc19d8fc1324fdfd862c2",
    "StatusIcon.dc.html": "d89e524bb53567b77c7508f49837c6fae6d363e2c77d369301cc3f02edf8411c",
}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    for name, expected in HASHES.items():
        assert hashlib.sha256((SOURCE / name).read_bytes()).hexdigest() == expected, name
    animations = (SOURCE / "Polly Animations.dc.html").read_text()
    bundle = (SOURCE / "Polly Animations.html").read_text()
    template = json.loads(re.search(r'<script type="__bundler/template">(.*?)</script>', bundle, re.S)[1])
    manifest = json.loads(re.search(r'<script type="__bundler/manifest">(.*?)</script>', bundle, re.S)[1])
    poses = re.findall(r'<svg viewBox="-24 -18 248 248".*?</svg>', animations, re.S)
    symbols = re.findall(r'<svg .*?</svg>', (SOURCE / "StatusIcon.dc.html").read_text(), re.S)
    frames = [line for line in animations.splitlines() if line.startswith("@keyframes")]
    assert len(poses) == len(symbols) == 4 and len(frames) == 15
    assert all(line in template for line in frames), "Bundled and editable animation timings differ"
    rules = []

    def external_styles(svg):
        def replace(match):
            name = f"design-{len(rules)}"
            rules.append(f".{name}{{{match[1]}}}")
            return f'class="{name}"'
        return re.sub(r'style="([^"]+)"', replace, svg)

    mascots = dict(zip(["ok", "warning", "critical", "unreachable"], map(external_styles, poses)))
    icons = dict(zip(["ok", "warning", "critical", "unknown"], [external_styles(svg.replace("{{fill}}", "var(--status-fill)").replace("{{glyph}}", "var(--status-glyph)")) for svg in symbols]))
    outputs = {
        "design.mjs": "// Generated by scripts/generate-web-design.py.\n" +
                      "export const mascots = " + json.dumps(mascots, indent=2) + ";\n" +
                      "export const icons = " + json.dumps(icons, indent=2) + ";\n",
        "design.css": "/* Generated from the original SVG styles and keyframes. */\n" + "\n".join(frames + rules) + "\n",
    }
    font_rules = re.findall(r'@font-face\s*\{[^}]+\}', template)
    assert len(font_rules) == 26
    fonts = set()
    def font_url(match):
        key = match[1]
        resource = manifest[key]
        assert resource["mime"] == "font/woff2" and not resource["compressed"]
        fonts.add(key)
        outputs[f"fonts/{key}.woff2"] = base64.b64decode(resource["data"])
        return f'url("fonts/{key}.woff2")'
    outputs["fonts.css"] = re.sub(r'url\("([^"]+)"\)', font_url, "\n".join(font_rules)) + "\n"
    assert len(fonts) == 11
    for name, contents in outputs.items():
        data = contents.encode() if isinstance(contents, str) else contents
        path = PUBLIC / name
        if options.check:
            assert path.read_bytes() == data, f"Regenerate {path}"
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f"✅ {'Checked' if options.check else 'Generated'} {len(outputs)} assets from five verified exports.")


if __name__ == "__main__":
    main()
